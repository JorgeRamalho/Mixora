export function seedClipFromMeta(
  platform: PlatformId,
  artist: string,
  title: string,
  overrides: Partial<RadioClip> = {},
): RadioClip {
  const youtubeId = resolveYoutubeId(artist, title) ?? "";
  return {
    id: overrides.id ?? `seed-${platform}-${title.toLowerCase().replace(/\s+/g, "-")}`,
    title,
    artist,
    genre: overrides.genre ?? "Electronic",
    bpm: overrides.bpm ?? 126,
    key: overrides.key ?? "—",
    duration: overrides.duration ?? "3:30",
    youtubeId,
    sourceUrl: overrides.sourceUrl ?? platformSearchUrl(platform, artist, title),
    caption: overrides.caption ?? `Catálogo ${platform} · Mamute FM.`,
    platform,
    ...overrides,
  };
}
